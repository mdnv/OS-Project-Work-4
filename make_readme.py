"""Build a submission README using actual measurements, not example numbers."""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def read_rows(task):
    with (ROOT / 'results' / f'{task}_results.csv').open(encoding='utf-8', newline='') as file:
        rows = list(csv.DictReader(file))
    if len(rows) != 3:
        raise ValueError(f'{task}: expected three methods')
    return rows


def conclusion(row, fast, slow):
    ratio = float(row['speedup'])
    prefix = f"Измеренное ускорение: {ratio:.2f}×. "
    return prefix + (fast if ratio > 1.05 else slow if ratio < 0.95 else
                     'В этой серии времена близки; заметного ускорения не наблюдалось.')


def main():
    cpu = read_rows('cpu')
    network = read_rows('network')
    cpu_text = (ROOT / 'results' / 'cpu_results.md').read_text(encoding='utf-8').replace('# Результаты: cpu', '## Вычисления', 1)
    net_text = (ROOT / 'results' / 'network_results.md').read_text(encoding='utf-8').replace('# Результаты: network', '## Сеть', 1)
    notes = [
        '**4 потока, сумма.** ' + conclusion(cpu[1],
            'В этой серии потоки оказались быстрее, но для обычного Python-цикла это не доказывает параллельное исполнение: GIL сохраняется. Следует учитывать шум измерений и нагрузку VM.',
            'Потоки не ускорили вычисления: GIL ограничивает одновременное выполнение Python-кода, а создание и переключение потоков добавляют расходы.'),
        '**4 процесса, сумма.** ' + conclusion(cpu[2],
            'Процессы ускорили вычисления: у каждого свой интерпретатор и GIL, поэтому части массива обрабатываются на нескольких доступных VM процессорах.',
            'Процессы оказались медленнее. Они обходят GIL, но запуск, обмен результатами и завершение имеют стоимость. Влияют число vCPU, нагрузка хоста и VM, пропускная способность памяти и размер задачи.'),
        '**ThreadPoolExecutor, сеть.** ' + conclusion(network[1],
            'Ожидание ответов перекрывается между потоками; при ожидании сокетного ввода-вывода GIL освобождается.',
            'Потоки не ускорили эту серию. Возможны малая задержка, ограничение параллелизма сервером или фоновые нагрузки; это не отменяет освобождение GIL при ожидании ввода-вывода.'),
        '**ProcessPoolExecutor, сеть.** ' + conclusion(network[2],
            'Процессы также перекрывают ожидание ответов, но требуют отдельного интерпретатора и обмена результатами.',
            'В этой серии расходы на процессы или особенности сервера перевесили пользу одновременных запросов.'),
    ]
    text = '''# Потоки и процессы: вариант B

## Что сделано

Сумма 10 млн целых чисел сравнивается в одном потоке, четырёх потоках threading и четырёх процессах multiprocessing. Загрузка 20 URL сравнивается последовательно, через ThreadPoolExecutor и ProcessPoolExecutor с четырьмя исполнителями. Каждый метод измеряется три раза через perf_counter; основная метрика — медиана. Порядок методов меняется между повторами. Ускорение = медиана последовательного метода / медиана данного метода.

Работа выполняется внутри Ubuntu в VirtualBox на MacBook Air M1, через SSH. Число доступных VM процессоров берётся из nproc и записывается в каждую строку таблицы. Число исполнителей может превышать число доступных процессоров; это не создаёт дополнительные ядра.

## Как работает измерение

Генерация данных не входит в замеры. Для CPU-задачи numbers.txt заранее загружается в array('q'); чтение и преобразование строк исключены, чтобы сравнить именно сложение. Во всех вариантах используется одинаковый Python-цикл. Четыре исполнителя обрабатывают четыре непересекающихся диапазона. Метод fork явно выбран для Ubuntu; дочерние процессы наследуют массив только для чтения, без пересылки 10 млн чисел. Это оптимизация конкретного эксперимента, а не универсальное поведение всех способов запуска процессов.

В замеры входят запуск исполнителей, получение результатов и их завершение. Последовательный вариант работает в главном потоке. Для сети измеряются запросы и полное чтение тел ответов; предварительная проверка URL исключена. Локальный сервер обрабатывает запросы одновременно; по умолчанию он добавляет 0,2 с ожидания перед ответом, моделируя задержку удалённого сервера. Это лабораторная модель, а не измерение скорости Интернета. Для обычного http.server задержки нет; сетевую среду указывают в --network-note.

Все суммы сверяются с контрольной суммой. Для URL сравниваются размеры каждого ответа с предварительным проходом; для локальных неизменных файлов это проверяет выполнение всех загрузок.

'''
    text += cpu_text + '\n' + net_text + '\n## Объяснение результатов\n\n' + '\n\n'.join(notes)
    text += '''

## Когда использовать потоки, когда процессы

Потоки подходят для задач с ожиданием ввода-вывода: HTTP-запросов, работы с сокетами, ожидания ответа базы данных. Они используют общую память и обычно имеют меньшие накладные расходы. Процессы подходят для достаточно крупных независимых вычислений на Python, если доступно несколько процессоров. Они обходят GIL, но требуют больше ресурсов и обмена данными. Для небольших задач последовательный вариант может быть быстрее обоих подходов. Эти выводы относятся к обычному CPython с GIL; библиотеки, освобождающие GIL, могут вести себя иначе.

## Общая и отдельная память

memory_demo.py изменяет глобальный список сначала в потоке, затем в дочернем процессе. Вывод:

```text
Parent before: []
Inside thread: ['thread']
Parent after thread: ['thread']
Inside process: ['thread', 'process']
Parent after process: ['thread']
```

Поток изменяет тот же список, который видит родитель. После fork дочерний процесс первоначально видит содержимое родителя, но его дальнейшее изменение обычного списка не меняет список в родителе. Linux использует copy-on-write; изначальное совместное использование физических страниц не означает общий изменяемый Python-список. Процессы могут обмениваться данными через Queue/Pipe, а общую память нужно организовать явно. Демонстрация после join не является примером безопасной синхронизации произвольных одновременных изменений списка.

## Контрольные вопросы

1. У потоков одного процесса общие адресное пространство, код, глобальные данные, куча и открытые файловые дескрипторы. У каждого свои стек вызовов, регистры, счётчик команд, состояние выполнения и локальные данные потока. Локальная переменная может ссылаться на общий объект; локальность имени не гарантирует изоляцию объекта.
2. В обычном CPython GIL разрешает выполнять Python-код одному потоку интерпретатора в данный момент. Поэтому четыре потока не дают параллельное сложение Python-чисел на четырёх ядрах. У отдельных процессов свои интерпретаторы и GIL, поэтому они могут считать одновременно. Реальное ускорение зависит от числа доступных CPU и от того, перекрывает ли работа расходы запуска и обмена результатами. При ожидании сокетного ввода-вывода GIL освобождается, поэтому потоки могут перекрывать ожидание ответов.

## Запуск

Без сторонних библиотек и pip. Все команды выполняются внутри Ubuntu:

```bash
python3 generate_data.py
python3 benchmark.py cpu
python3 memory_demo.py
```

Во второй SSH-вкладке запустить сервер и оставить работающим:

```bash
cd ~/os-threads-lab
python3 server.py
```

В первой вкладке:

```bash
python3 benchmark.py network
python3 make_readme.py
```

Результаты сохранены в results/cpu_results.csv, results/cpu_results.md, results/network_results.csv и results/network_results.md. После изменения режима сервера повторить сетевые измерения с верным --network-note, затем пересоздать README. numbers.txt расположен в data/. Для предоставленного преподавателем файла используется --numbers; для предоставленного списка URL — --urls.
'''
    (ROOT / 'README.md').write_text(text, encoding='utf-8')
    print('README.md created using your actual measurements.')


if __name__ == '__main__':
    main()
